// Run only against a disposable database: SAVDOCHI_TEST_URL=http://... node tests/integration.mjs
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
const base=process.env.SAVDOCHI_TEST_URL;
if(!base)throw new Error('Set SAVDOCHI_TEST_URL for a disposable test environment');
const suffix=randomUUID();
function client(){let cookie='';return async(path,method='GET',body,expected=200)=>{
 const r=await fetch(base+path,{method,headers:{'content-type':'application/json',...(cookie?{cookie}:{})},...(body?{body:JSON.stringify(body)}:{})});
 if(r.headers.get('set-cookie'))cookie=r.headers.get('set-cookie').split(';')[0];
 const d=await r.json();assert.equal(r.status,expected,`${method} ${path}: ${JSON.stringify(d)}`);return d;
};}
const seller=client(),other=client(),buyer=client(),anonymous=client();
const creds=role=>({name:'QA '+role,email:role+'-'+suffix+'@example.invalid',password:'Test-'+randomUUID(),role:role==='buyer'?'buyer':'seller'});
await seller('/api/auth/register','POST',creds('seller'),201);
await other('/api/auth/register','POST',creds('other'),201);
const buyerCreds=creds('buyer');await buyer('/api/auth/register','POST',buyerCreds,201);
const product={name:'QA Guruch',category:'Oziq-ovqat',price:12000,unit:'1 kg',stock:20,minOrder:2,description:'Integration test'};
const p=(await seller('/api/products','POST',product,201)).product;
const q=(await other('/api/products','POST',{...product,name:'QA Un'},201)).product;
await anonymous('/api/products','POST',product,401);
await buyer('/api/products','POST',product,403);
await other('/api/products/'+p.id,'PATCH',product,404);
await other('/api/products/'+p.id,'DELETE',undefined,404);
await seller('/api/products','POST',{...product,price:-1},400);
assert.ok((await anonymous('/api/products')).products.some(x=>x.id===p.id));
console.log('PASS products: create, public catalog, ownership and role checks');
const payload={requestId:randomUUID(),phone:'+998901234567',address:'QA Test address',items:[{productId:p.id,quantity:3},{productId:q.id,quantity:4}]};
const created=(await buyer('/api/orders','POST',payload,201)).orders;
assert.equal(created.length,2);assert.equal(created.reduce((n,o)=>n+o.total,0),84000);
const retried=(await buyer('/api/orders','POST',payload,201)).orders;
assert.deepEqual(retried.map(o=>o.id).sort(),created.map(o=>o.id).sort());
let inventory=(await anonymous('/api/products')).products;assert.equal(inventory.find(x=>x.id===p.id).stock,17);
const own=(await seller('/api/orders')).orders;assert.equal(own.length,1);
await other('/api/orders/'+own[0].id,'PATCH',{status:'confirmed'},404);
await buyer('/api/orders/'+own[0].id,'PATCH',{status:'confirmed'},409);
await seller('/api/orders/'+own[0].id,'PATCH',{status:'delivered'},409);
await seller('/api/orders/'+own[0].id,'PATCH',{status:'confirmed'});
await buyer('/api/orders/'+own[0].id,'PATCH',{status:'cancelled'},409);
await seller('/api/orders/'+own[0].id,'PATCH',{status:'shipped'});
await seller('/api/orders/'+own[0].id,'PATCH',{status:'delivered'});
const otherOrder=created.find(o=>o.id!==own[0].id);
await buyer('/api/orders/'+otherOrder.id,'PATCH',{status:'cancelled'});
await buyer('/api/orders/'+otherOrder.id,'PATCH',{status:'cancelled'});
inventory=(await anonymous('/api/products')).products;assert.equal(inventory.find(x=>x.id===q.id).stock,20);
console.log('PASS multi-seller checkout, totals, retry deduplication, state transitions, single restock');
await buyer('/api/orders','POST',{...payload,requestId:randomUUID(),items:[{productId:p.id,quantity:2},{productId:q.id,quantity:999}]},409);
assert.equal((await anonymous('/api/products')).products.find(x=>x.id===p.id).stock,17);
console.log('PASS transaction rollback: insufficient item does not reserve other items');
const last=(await seller('/api/products','POST',{...product,stock:2},201)).product;
const race=()=>buyer('/api/orders','POST',{...payload,requestId:randomUUID(),items:[{productId:last.id,quantity:2}]},201);
const outcomes=await Promise.allSettled([race(),race()]);assert.equal(outcomes.filter(r=>r.status==='fulfilled').length,1);
assert.equal((await anonymous('/api/products')).products.find(x=>x.id===last.id).stock,0);
console.log('PASS concurrent checkout cannot oversell');
await seller('/api/products/'+p.id,'PATCH',{...product,price:20000,stock:17});
assert.equal((await buyer('/api/orders')).orders.find(o=>o.id===own[0].id).items[0].price,12000);
await seller('/api/products/'+p.id,'DELETE');
assert.ok(!(await anonymous('/api/products')).products.some(x=>x.id===p.id));
assert.ok((await buyer('/api/orders')).orders.some(o=>o.id===own[0].id));
await buyer('/api/auth/logout','POST');await buyer('/api/orders','GET',undefined,401);
await buyer('/api/auth/login','POST',{email:buyerCreds.email,password:buyerCreds.password});
assert.ok((await buyer('/api/orders')).orders.length>=2);
console.log('PASS price snapshots, product deletion, order history, logout and login');
